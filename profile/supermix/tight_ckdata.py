"""Write a copy of SuperMix's ckdata.cc with a much tighter Bessel tolerance.

Stock SuperMix truncates the Bessel functions and phase factors at
ZEROTOL = 1e-6 (and picks the Bessel order with a fit that is only valid for
that value). This copy uses ZEROTOL = 1e-14 and a generous Bessel order, so
that SuperMix and QMix can be compared to machine precision. Linking the
compiled copy ahead of libMiX.a overrides the library's ckdata.o.

Usage: python tight_ckdata.py <supermix_dir> <output.cc>
"""

import sys

src_path, out_path = sys.argv[1] + '/lib-src/ckdata.cc', sys.argv[2]
src = open(src_path).read()

src = src.replace('#include <cmath>\n', '#include <cmath>\n#undef ZEROTOL\n#define ZEROTOL (1.0e-14)\n', 1)

start = src.index('  int nmax;  // the maximum order')
end = src.index('  // now reallocate bessel_values')
src = src[:start] + '  int nmax = int(30 + 1.5 * x);  // generous order for ZEROTOL = 1e-14\n\n' + src[end:]

with open(out_path, 'w') as fout:
    fout.write('// GENERATED by tight_ckdata.py from SuperMix lib-src/ckdata.cc -- do not edit\n')
    fout.write(src)
