"""Compare QMix with SuperMix (Caltech's C++ SIS mixer library).

Both codes are run on identical inputs and the differences are printed:

1. Tunneling current: the junction voltage is given (bias voltage plus LO
   harmonics with arbitrary amplitude and phase) and the dc and ac tunneling
   currents are compared (``qmix.qtcurrent.qtcurrent`` vs
   ``sis_device::large_signal``).

2. Harmonic balance: a single-tone Thevenin embedding circuit (one vt, zt
   per harmonic) is solved by both codes and the junction voltages and
   currents are compared (``qmix.harmonic_balance.harmonic_balance`` vs
   ``mixer::balance``).

The response function is generated by QMix and exported as SuperMix I-V data
files (dense tables of Idc and Ikk), so both codes use the same I-V curve up
to interpolation error. QMix's KK transform does not vanish at v = 0 like the
Tucker form that SuperMix expects, but a constant offset in Ikk cancels out of
the tunneling currents, so this does not matter.

Two things limit the agreement, and each case is run twice to separate them:

- QMix's interpolated response function is symmetric (Idc odd, Ikk even)
  only to within its interpolation error, while SuperMix mirrors the v >= 0
  data. This gives up to ~1e-5 in the ac currents. The second run wraps the
  QMix response function in ``SymmetricResp`` so both codes see one curve.
- Stock SuperMix truncates the Bessel functions and phase factors at 1e-6
  (ZEROTOL in its global.h). ``./build.sh --tight`` also builds a driver with
  this set to 1e-14; with it and the symmetrized response function, the
  tunneling currents agree to ~1e-15 and the harmonic balance to QMix's
  stopping tolerance.

QMix is run with generous num_b so that its truncation error is negligible.

Usage (from this directory)::

    ./build.sh --tight smx_driver.cc               # build both drivers
    python compare.py                              # stock SuperMix
    SMX_DRIVER=bin/smx_driver_tight python compare.py
    python compare.py --plot                       # also save plots to work/

"""

import argparse
import os
import subprocess
import sys
from timeit import default_timer as timer

import numpy as np

import qmix
from qmix.harmonic_balance import harmonic_balance
from qmix.qtcurrent import qtcurrent, suggest_num_b

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(HERE, 'work')
DRIVER = os.environ.get('SMX_DRIVER', os.path.join(HERE, 'bin', 'smx_driver'))

# Normalizing values passed to SuperMix (results are normalized, so these
# only need to be self-consistent)
VN_MV = 2.8
RN_OHM = 10.

# Exported I-V table: dense, and wide enough that SuperMix never has to
# extrapolate (it uses its own log extrapolation for Ikk beyond the table).
# The step (0.0005) divides the bias step and the LO frequencies used below,
# so every voltage vb + k * flo that either code evaluates is a table point:
# SuperMix's spline then returns QMix's values exactly and interpolation
# error drops out of the comparison.
V_TABLE = np.linspace(0, 20, 40001)

# Prepended to plot titles and file names (set per run in main)
PLOT_PREFIX = ''


# Response function export ---------------------------------------------------

class SymmetricResp(object):
    """Response function made exactly symmetric: Idc odd, Ikk even.

    SuperMix only reads I-V data for v >= 0 and mirrors it. QMix's
    interpolated response function is symmetric only to within its
    interpolation error (its spline knots are not placed symmetrically
    about v = 0), which gives differences up to ~1e-5 in the ac currents.
    Wrapping the QMix response function in this class gives both codes the
    same curve, so that the comparison isolates the algorithms.
    """

    def __init__(self, resp):
        self._resp = resp

    def __call__(self, vbias):
        vbias = np.asarray(vbias, dtype=float)
        r = self._resp(np.abs(vbias))
        return r.real + 1j * np.sign(vbias) * r.imag

    resp = __call__


def export_respfn(resp, name):
    """Write the QMix response function as SuperMix Idc and Ikk files."""

    os.makedirs(WORK, exist_ok=True)
    r = resp(V_TABLE)
    files = []
    for label, values in (('idc', r.imag), ('ikk', r.real)):
        path = os.path.join(WORK, '{}_{}.dat'.format(name, label))
        np.savetxt(path, np.c_[V_TABLE, values], fmt='%.17g',
                   header='{} exported from QMix (normalized)'.format(label))
        files.append(path)
    return files


# SuperMix driver ------------------------------------------------------------

def run_supermix(lines):
    """Run the SuperMix driver on the given input lines; parse its output."""

    if not os.path.isfile(DRIVER):
        sys.exit("SuperMix driver not found; run ./build.sh smx_driver.cc first")

    result = subprocess.run([DRIVER], input='\n'.join(lines) + '\n', capture_output=True, text=True, check=True)
    rows, time_s = [], None
    for line in result.stdout.splitlines():
        if line.startswith('# time_s'):
            time_s = float(line.split()[2])
        elif line.strip():
            rows.append([float(x) for x in line.split()])
    data = np.array(rows)

    num_p = (data.shape[1] - 3) // 4 - 1
    out = {'vb': data[:, 0], 'iterations': data[:, 1].astype(int), 'status': data[:, 2].astype(int),
           'time': time_s}
    vals = data[:, 3:].reshape(len(data), num_p + 1, 4)
    out['vj'] = (vals[:, :, 0] + 1j * vals[:, :, 1]).T  # [p, i]
    out['ij'] = (vals[:, :, 2] + 1j * vals[:, :, 3]).T
    return out


def _fmt(z):
    return '{:.17g} {:.17g}'.format(z.real, z.imag)


def supermix_current(files, flo, vb, vj):
    """SuperMix tunneling current for given junction voltages vj[p, i]."""

    num_p = vj.shape[0] - 1
    lines = ['current {} {} {} {}'.format(VN_MV, RN_OHM, *files),
             '{:.17g} {} {}'.format(flo, num_p, len(vb))]
    for i, v0 in enumerate(vb):
        lines.append('{:.17g} '.format(v0) + ' '.join(_fmt(vj[p, i]) for p in range(1, num_p + 1)))
    return run_supermix(lines)


def supermix_balance(files, flo, vb, vt, zt, tol=1e-12):
    """SuperMix harmonic balance; vt[p], zt[p] for p = 1..num_p."""

    num_p = len(vt) - 1
    lines = ['balance {} {} {} {}'.format(VN_MV, RN_OHM, *files),
             '{:.17g} {} {}'.format(flo, num_p, len(vb)),
             '{:.17g}'.format(tol)]
    for p in range(1, num_p + 1):
        lines.append(_fmt(vt[p]) + ' ' + _fmt(zt[p]))
    lines += ['{:.17g}'.format(v0) for v0 in vb]
    return run_supermix(lines)


# QMix -----------------------------------------------------------------------

def make_circuit(flo, num_p, vb):
    cct = qmix.circuit.EmbeddingCircuit(1, num_p, vb_min=vb[0], vb_max=vb[-1], vb_npts=len(vb))
    cct.freq[1] = flo
    assert np.allclose(cct.vb, vb)
    return cct


def qmix_current(resp, cct, vj, num_b):
    """QMix dc and ac tunneling currents, ij[p, i] (peak phasors)."""

    vj3 = np.zeros((2, cct.num_p + 1, cct.vb_npts), dtype=complex)
    vj3[1, 1:] = vj[1:]
    freq_list = [p * cct.freq[1] for p in range(cct.num_p + 1)]
    return qtcurrent(vj3, cct, resp, freq_list, num_b=num_b, verbose=False)


# Cases ----------------------------------------------------------------------

def compare_current(resp, files, name, flo, vph_list, num_p_amps, plot=False):
    """Tunneling current with a given junction voltage.

    Args:
        vph_list: complex junction voltage for each harmonic p = 1..num_p
            (constant over the bias sweep)
    """

    vb = np.linspace(0, 2, 401)
    num_p = len(vph_list)
    vj = np.zeros((num_p + 1, len(vb)), dtype=complex)
    vj[0] = vb
    vj[1:] = np.array(vph_list)[:, None]

    cct = make_circuit(flo, num_p, vb)
    vj3 = np.zeros((2, num_p + 1, len(vb)), dtype=complex)
    vj3[1, 1:] = vj[1:]
    num_b = suggest_num_b(vj3, cct, tol=1e-12, max_b=60)

    t0 = timer()
    ij_q = qmix_current(resp, cct, vj, num_b)
    t_qmix = timer() - t0
    smx = supermix_current(files, flo, vb, vj)

    assert np.allclose(smx['vj'][0], vb) and np.allclose(smx['vj'][1:], vj[1:])
    ij_s = smx['ij']

    print('\n{} (num_b = {})'.format(name, num_b[0]))
    print('  {:>4s}  {:>12s}  {:>12s}'.format('p', 'max |I|', 'max |diff|'))
    for p in range(num_p + 1):
        diff = np.abs(ij_q[p] - ij_s[p])
        print('  {:>4d}  {:12.3e}  {:12.3e}'.format(p, np.abs(ij_q[p]).max(), diff.max()))
    print('  time: QMix {:.4f} s (all points), SuperMix {:.4f} s'.format(t_qmix, smx['time']))

    if plot:
        _plot(name, vb, ij_q, ij_s, 'Tunneling current')

    return np.abs(ij_q - ij_s).max()


def compare_balance(resp, files, name, flo, vt_list, zt_list, plot=False):
    """Harmonic balance with a Thevenin circuit (one vt, zt per harmonic)."""

    vb = np.linspace(0.02, 2, 199)
    num_p = len(vt_list)
    vt = np.r_[0, vt_list].astype(complex)
    zt = np.r_[0, zt_list].astype(complex)

    cct = make_circuit(flo, num_p, vb)
    cct.vt[1, 1:] = vt[1:]
    cct.zt[1, 1:] = zt[1:]

    # QMix: solve once with a conservative num_b, then refine
    t0 = timer()
    vj3 = harmonic_balance(cct, resp, num_b=30, max_it=50, stop_rerror=1e-9, verbose=False)
    num_b = suggest_num_b(vj3, cct, tol=1e-12, max_b=60)
    vj3, it_q, ok_q = harmonic_balance(cct, resp, num_b=num_b, max_it=50, stop_rerror=1e-10, vj_initial=vj3,
                                       verbose=False, mode='x')
    t_qmix = timer() - t0
    vj_q = np.zeros((num_p + 1, len(vb)), dtype=complex)
    vj_q[0] = vb
    vj_q[1:] = vj3[1, 1:]
    ij_q = qmix_current(resp, cct, vj_q, num_b)

    smx = supermix_balance(files, flo, vb, vt, zt)
    vj_s, ij_s = smx['vj'], smx['ij']

    # Check that each solution satisfies its own circuit
    res_q = np.abs(vt[1:, None] - zt[1:, None] * ij_q[1:] - vj_q[1:]).max()
    res_s = np.abs(vt[1:, None] - zt[1:, None] * ij_s[1:] - vj_s[1:]).max()

    print('\n{} (num_b = {})'.format(name, num_b[0]))
    print('  converged: QMix {} ({} it.), SuperMix {}/{} points (median {} it., max {})'.format(
          ok_q, it_q, np.sum(smx['status'] == 0), len(vb), int(np.median(smx['iterations'])),
          smx['iterations'].max()))
    print('  circuit residual max |vt - zt*ij - vj|: QMix {:.1e}, SuperMix {:.1e}'.format(res_q, res_s))
    print('  {:>4s}  {:>12s}  {:>12s}  {:>12s}  {:>12s}'.format('p', 'max |V|', 'max |dV|', 'max |I|', 'max |dI|'))
    for p in range(num_p + 1):
        print('  {:>4d}  {:12.3e}  {:12.3e}  {:12.3e}  {:12.3e}'.format(
              p, np.abs(vj_q[p]).max(), np.abs(vj_q[p] - vj_s[p]).max(),
              np.abs(ij_q[p]).max(), np.abs(ij_q[p] - ij_s[p]).max()))
    print('  time: QMix {:.3f} s (two passes, all points), SuperMix {:.4f} s'.format(t_qmix, smx['time']))

    if plot:
        _plot(name, vb, ij_q, ij_s, 'Junction current')
        _plot(name + ' voltage', vb, vj_q, vj_s, 'Junction voltage')

    return max(np.abs(vj_q - vj_s).max(), np.abs(ij_q - ij_s).max())


def _plot(name, vb, q, s, ylabel):
    import matplotlib.pyplot as plt

    num_p = q.shape[0] - 1
    fig, axes = plt.subplots(2, num_p + 1, figsize=(4 * (num_p + 1), 6), sharex=True, squeeze=False)
    for p in range(num_p + 1):
        ax, axd = axes[0, p], axes[1, p]
        ax.plot(vb, np.abs(q[p]), 'k', label='QMix')
        ax.plot(vb, np.abs(s[p]), 'r--', label='SuperMix')
        ax.set_title('p = {}'.format(p))
        axd.semilogy(vb, np.abs(q[p] - s[p]) + 1e-18, 'b')
        axd.set_xlabel('Bias voltage')
    axes[0, 0].set_ylabel(ylabel + ' magnitude')
    axes[1, 0].set_ylabel('|QMix - SuperMix|')
    axes[0, 0].legend()
    fig.suptitle(name)
    fig.tight_layout()
    name = PLOT_PREFIX + name
    path = os.path.join(WORK, name.replace(' ', '_').replace(',', '') + '.png')
    fig.savefig(path, dpi=120)
    plt.close(fig)
    print('  plot: {}'.format(os.path.relpath(path, HERE)))


# Main -----------------------------------------------------------------------

def main():

    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--plot', action='store_true', help='save plots to work/')
    args = parser.parse_args()

    resp_raw = qmix.respfn.RespFnPolynomial(50, verbose=False)
    files = export_respfn(resp_raw, 'poly50')

    global PLOT_PREFIX
    worst = {}
    for label, resp, prefix in (('QMix response function', resp_raw, 'raw resp, '),
                                ('symmetrized response function', SymmetricResp(resp_raw), 'sym resp, ')):
        PLOT_PREFIX = prefix

        print('\n' + '#' * 72)
        print('# QMix uses the {}'.format(label))
        print('#' * 72)

        print('\nTunneling current (junction voltage given)')
        print('-' * 72)
        for alpha in (0.5, 1.0, 3.0):
            name = 'current, 1 harmonic, alpha {}'.format(alpha)
            worst[label, name] = compare_current(resp, files, name, 0.3, [alpha * 0.3], 1, plot=args.plot)
        name = 'current, 3 harmonics with phases'
        vph = [0.35, 0.08 * np.exp(0.7j), 0.03 * np.exp(-1.2j)]
        worst[label, name] = compare_current(resp, files, name, 0.33, vph, 3, plot=args.plot)

        print('\nHarmonic balance (Thevenin circuit per harmonic)')
        print('-' * 72)
        name = 'balance, 1 harmonic'
        worst[label, name] = compare_balance(resp, files, name, 0.3, [0.5], [0.3 - 0.3j], plot=args.plot)
        name = 'balance, 3 harmonics'
        worst[label, name] = compare_balance(resp, files, name, 0.3, [0.5, 0, 0],
                                             [0.3 - 0.3j, 0.1 - 0.2j, 0.05 - 0.1j], plot=args.plot)

    print('\n' + '=' * 72)
    print('Summary: max |QMix - SuperMix| (normalized units)')
    print('=' * 72)
    print('  {:<36s} {:>12s} {:>12s}'.format('case', 'QMix resp', 'symmetrized'))
    names = [name for (label, name) in worst if label == 'QMix response function']
    for name in names:
        err_raw = worst['QMix response function', name]
        err_sym = worst['symmetrized response function', name]
        print('  {:<36s} {:12.2e} {:12.2e}'.format(name, err_raw, err_sym))


if __name__ == '__main__':
    main()
